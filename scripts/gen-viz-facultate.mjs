#!/usr/bin/env node
// Builds src/components/lesson/viz/logic/facultate.js from the lab dataset, so the
// visual widgets can show their pure step logic without the SQL engine.
import { readFileSync, writeFileSync } from 'fs';

const sql = readFileSync('public/sql/datasets/facultate.sql', 'utf-8');
const cols = {};
for (const m of sql.matchAll(/CREATE TABLE (\w+)\(([\s\S]*?)\)\s*;/gi)) {
  cols[m[1].toLowerCase()] = m[2].split(',').map(c => c.trim().split(/\s+/)[0].toLowerCase());
}
const tables = {};
const seen = new Set();
for (const line of sql.split('\n')) {
  const m = line.match(/^INSERT INTO (\w+)\s*VALUES\s*\((.*)\);\s*$/i);
  if (!m) continue;
  const name = m[1].toLowerCase();
  if (!['studenti', 'cursuri', 'note', 'didactic', 'profesori'].includes(name)) continue;
  const vals = [];
  const re = /TO_DATE\('([^']*)',\s*'[^']*'\)|'([^']*)'|(-?\d+(?:\.\d+)?)|(null)/gi;
  let v;
  while ((v = re.exec(m[2]))) {
    if (v[1] !== undefined) { const [d, mo, y] = v[1].split('/'); vals.push(`${y}-${mo.padStart(2, '0')}-${d.padStart(2, '0')}`); }
    else if (v[2] !== undefined) vals.push(v[2]);
    else if (v[3] !== undefined) vals.push(Number(v[3]));
    else vals.push(null);
  }
  const key = name + JSON.stringify(vals);
  if (name === 'profesori' && seen.has(name + vals[0])) continue; // later p20/p21 rows are a separate lab exercise
  seen.add(name + vals[0]);
  if (seen.has(key + '#')) continue;
  seen.add(key + '#');
  (tables[name] ||= []).push(Object.fromEntries(cols[name].map((c, i) => [c, vals[i]])));
}
const out = `// Generated by scripts/gen-viz-facultate.mjs from public/sql/datasets/facultate.sql. Do not edit.
export const FACULTATE = ${JSON.stringify(tables)};
`;
writeFileSync('src/components/lesson/viz/logic/facultate.js', out);
console.log(Object.entries(tables).map(([k, v]) => `${k}:${v.length}`).join(' '));
